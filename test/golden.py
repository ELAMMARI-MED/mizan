def bare(s):
    """تطبيع الاسم: إزالة الحركات و«بحر» وتوحيد الألف/الياء/التاء."""
    s = unicodedata.normalize('NFKC', s or '')
    s = ''.join(ch for ch in s if not ('\u064b' <= ch <= '\u0652'))
    s = s.replace('أ', 'ا').replace('إ', 'ا').replace('آ', 'ا')
    s = s.replace('ى', 'ي').replace('ة', 'ه')
    s = s.replace('ـ', '')
    if s.startswith('بحر'):
        s = s[3:]
    return ' '.join(s.split())


def main():
    verbose = '-v' in sys.argv
    passed = failed = 0
    for name, sadr, ajuz in GOLDEN:
        try:
            v = analyze_one(sadr, ajuz)
        except Exception as e:  # noqa: BLE001
            print(f'  ✗ {name}: انفجار المحرك — {e}')
            failed += 1
            continue
        got = v.get('meter_ar') or ''
        ok = bare(got) == bare(name)
        if ok:
            passed += 1
            if verbose:
                print(f'  ✓ {name} — {got} ({v.get("bahr_type")}) score={v.get("score")}')
        else:
            failed += 1
            print(f'  ✗ {name}: المحرك قال «{got}» — مطابقة ' +
                  f'{Math_pct(v.get("score"))} · صحيح؟ {v.get("is_valid")}')
            if verbose and v.get('explain'):
                e = v['explain']
                print(f'      أول تفعيلة مخالفة: {e["side"]} {e["foot_index"]} «{e["text"]}» ' +
                      f'{e["actual"]} مقابل {e["base"]} ({e["zihaf_ar"]})')
    print()
    print(f'النتيجة: {passed} ناجح · {failed} فاشل من {len(GOLDEN)}')
    return 0 if failed == 0 else 1


def Math_pct(score):
    try:
        return f'{round(float(score) * 100)}٪'
    except Exception:  # noqa: BLE001
        return '؟'


if __name__ == '__main__':
    sys.exit(main())